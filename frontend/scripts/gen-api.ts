// Regenerates src/api/schema.d.ts from the backend's OpenAPI document.
// Reads a running backend when one is up, otherwise builds the document from the backend's
// own registry so the step works in CI without starting the server.
import { writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const out = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));
const backend = fileURLToPath(new URL('../../backend', import.meta.url));
const url = process.env.OPENAPI_URL ?? 'http://localhost:4000/openapi.json';

async function document(): Promise<string> {
  try {
    const res = await fetch(url);
    if (res.ok) return await res.text();
  } catch {
    // not running; fall through
  }
  return execFileSync(
    'node',
    [
      '--import',
      'tsx',
      '-e',
      'import("./src/openapi/registry.ts").then(m => console.log(JSON.stringify(m.openApiDocument())))',
    ],
    {
      cwd: backend,
      encoding: 'utf8',
      env: { ...process.env, NODE_ENV: 'test' },
      maxBuffer: 64 * 1024 * 1024,
    },
  );
}

const ast = await openapiTS(JSON.parse(await document()), { alphabetize: true });
const header = '// Generated by `pnpm gen:api` from the backend OpenAPI document. Do not edit.\n';
await writeFile(out, header + astToString(ast));
console.log(`wrote ${out}`);
