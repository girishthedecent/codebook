import { useEffect, useState } from 'react';

/**
 * How many pixels of the layout viewport the on-screen keyboard covers, from the visual
 * viewport. 0 when no keyboard is up, or when the browser has no visualViewport.
 */
export function useKeyboardInset() {
  const [inset, setInset] = useState(0);

  useEffect(() => {
    const vv = window.visualViewport;
    if (!vv) return;
    const update = () => {
      const covered = window.innerHeight - vv.height - vv.offsetTop;
      // Small differences are browser chrome sliding in and out, not a keyboard.
      setInset(covered > 80 ? Math.round(covered) : 0);
    };
    update();
    vv.addEventListener('resize', update);
    vv.addEventListener('scroll', update);
    return () => {
      vv.removeEventListener('resize', update);
      vv.removeEventListener('scroll', update);
    };
  }, []);

  return inset;
}
